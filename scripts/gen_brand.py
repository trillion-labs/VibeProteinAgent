"""Wire the chosen brand mark (F1 'Classic' robot) into the repo.

Reads the agreed concept SVG and emits:
  * ``assets/readme/vpa-logo.svg``                  -- canonical standalone mark
  * ``src/vibeproteinagent/reporting/_brand.py``    -- inline-SVG helper for the
                                                       HTML report
  * patches ``assets/readme/vpa-report-snapshot.svg`` -- swaps the old benzene
                                                       mark for the robot logo

Re-run after changing the concept in ``scripts/gen_robot_faces.py``.
"""
from __future__ import annotations

from pathlib import Path

import cairosvg

ROOT = Path(__file__).resolve().parent.parent
CONCEPT = ROOT / "assets/readme/logo-concepts/robot-faces/f1-classic.svg"

raw = CONCEPT.read_text(encoding="utf-8")
inner = raw.split(">", 1)[1].rsplit("</svg>", 1)[0]
inner = " ".join(inner.split())                       # tidy to one line
# namespace the gradient ids so the mark can be inlined alongside other SVGs
inner = (inner.replace('id="tile"', 'id="vpaTileGrad"')
              .replace("url(#tile)", "url(#vpaTileGrad)")
              .replace('id="glow"', 'id="vpaGlowGrad"')
              .replace("url(#glow)", "url(#vpaGlowGrad)"))

# --- canonical standalone asset ----------------------------------------------
logo = ROOT / "assets/readme/vpa-logo.svg"
logo.write_text(
    '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" '
    f'viewBox="0 0 256 256">{inner}</svg>\n',
    encoding="utf-8",
)
print(f"wrote {logo.relative_to(ROOT)}")

# --- inline-SVG helper for the HTML report -----------------------------------
brand_py = ROOT / "src/vibeproteinagent/reporting/_brand.py"
brand_py.write_text(
    '"""VibeProteinAgent brand mark -- generated by scripts/gen_brand.py.\n\n'
    "Do not edit by hand; re-run the script to regenerate.\n"
    '"""\n'
    "# The brand SVG is emitted as one long literal line by the generator.\n"
    "# ruff: noqa: E501\n"
    "from __future__ import annotations\n\n"
    "_LOGO_INNER = " + repr(inner) + "\n\n\n"
    "def vpa_logo(css_class: str) -> str:\n"
    '    """Return the brand mark as an inline ``<svg>`` with *css_class*."""\n'
    "    return (\n"
    "        f'<svg class=\"{css_class}\" viewBox=\"0 0 256 256\" '\n"
    "        f'xmlns=\"http://www.w3.org/2000/svg\" aria-hidden=\"true\">'\n"
    "        f'{_LOGO_INNER}</svg>'\n"
    "    )\n",
    encoding="utf-8",
)
print(f"wrote {brand_py.relative_to(ROOT)}")

# --- patch the static README SVGs --------------------------------------------
def patch(rel: str, old: str, new: str) -> None:
    p = ROOT / rel
    text = p.read_text(encoding="utf-8")
    if old in text:
        p.write_text(text.replace(old, new, 1), encoding="utf-8")
        print(f"patched {rel}")
    elif new[:42] in text:
        print(f"{rel} already patched -- skipped")
    else:
        raise SystemExit(f"ERROR: benzene mark not found in {rel}")


patch(
    "assets/readme/vpa-report-snapshot.svg",
    '  <g transform="translate(40, 80)">\n'
    '    <rect width="32" height="32" rx="8" fill="url(#brandG)"/>\n'
    '    <g fill="none" stroke="#ffffff" stroke-width="1.6" stroke-linejoin="round" '
    'stroke-linecap="round" transform="translate(0, 0)">\n'
    '      <polygon points="26,16 21.2,7.1 10.8,7.1 6,16 10.8,24.9 21.2,24.9"/>\n'
    '      <circle cx="16" cy="16" r="6.2"/>\n'
    '    </g>\n'
    '  </g>',
    f'  <g transform="translate(40, 80) scale(0.125)">{inner}</g>',
)

patch(
    "assets/readme/vpa-hero.svg",
    '  <!-- brand mark: benzene ring (hexagon outline + inner aromatic circle) -->\n'
    '  <g transform="translate(112, 122)">\n'
    '    <rect width="56" height="56" rx="14" fill="#6b1ea8"/>\n'
    '    <g fill="none" stroke="#ffffff" stroke-width="2.4" stroke-linejoin="round" '
    'stroke-linecap="round">\n'
    '      <polygon points="46,28 37,12.4 19,12.4 10,28 19,43.6 37,43.6"/>\n'
    '      <circle cx="28" cy="28" r="11"/>\n'
    '    </g>\n'
    '  </g>',
    '  <!-- brand mark: VibeProteinAgent robot logo -->\n'
    f'  <g transform="translate(112, 122) scale(0.21875)">{inner}</g>',
)

# --- refresh the rasterised hero used by the README --------------------------
cairosvg.svg2png(
    url=str(ROOT / "assets/readme/vpa-hero.svg"),
    write_to=str(ROOT / "assets/readme/vpa-hero.png"),
    output_width=1672, output_height=560,
)
print("rendered assets/readme/vpa-hero.png")
